def percentile(values: Sequence[float], probability: float) -> float:
    if not values:
        raise ValueError("percentile_of_empty_sequence")
    ordered = sorted(values)
    position = probability * (len(ordered) - 1)
    low = math.floor(position)
    high = math.ceil(position)
    if low == high:
        return ordered[low]
    fraction = position - low
    return ordered[low] * (1.0 - fraction) + ordered[high] * fraction


def average_ranks(values: Sequence[float]) -> list[float]:
    order = sorted(range(len(values)), key=lambda i: (values[i], i))
    ranks = [0.0] * len(values)
    start = 0
    while start < len(order):
        end = start + 1
        while end < len(order) and values[order[end]] == values[order[start]]:
            end += 1
        rank = (start + 1 + end) / 2.0
        for index in order[start:end]:
            ranks[index] = rank
        start = end
    return ranks


def pearson(x: Sequence[float], y: Sequence[float]) -> float:
    if len(x) != len(y) or len(x) < 2:
        raise ValueError("pearson_requires_equal_sequences_of_length_at_least_two")
    mx, my = statistics.mean(x), statistics.mean(y)
    dx = [v - mx for v in x]
    dy = [v - my for v in y]
    denominator = math.sqrt(sum(v * v for v in dx) * sum(v * v for v in dy))
    return sum(a * b for a, b in zip(dx, dy)) / denominator if denominator else 1.0


def spearman_rho(x: Sequence[float], y: Sequence[float]) -> float:
    return pearson(average_ranks(x), average_ranks(y))


def kendall_tau_b(x: Sequence[float], y: Sequence[float]) -> float:
    if len(x) != len(y) or len(x) < 2:
        raise ValueError("kendall_requires_equal_sequences_of_length_at_least_two")
    concordant = discordant = ties_x = ties_y = 0
    for i in range(len(x) - 1):
        for j in range(i + 1, len(x)):
            dx = (x[i] > x[j]) - (x[i] < x[j])
            dy = (y[i] > y[j]) - (y[i] < y[j])
            if dx == 0 and dy == 0:
                continue
            if dx == 0:
                ties_x += 1
            elif dy == 0:
                ties_y += 1
            elif dx == dy:
                concordant += 1
            else:
                discordant += 1
    denominator = math.sqrt((concordant + discordant + ties_x) * (concordant + discordant + ties_y))
    return (concordant - discordant) / denominator if denominator else 1.0


def rank_descending(scores: dict[str, float]) -> dict[str, float]:
    names = sorted(scores)
    ascending = average_ranks([-scores[name] for name in names])
    return dict(zip(names, ascending))


def stable_seed_offset(*parts: str) -> int:
    payload = "\x1f".join(parts).encode("utf-8")
    return int(hashlib.sha256(payload).hexdigest()[:8], 16)


def paired_case_rank_bootstrap(
    scores_a: dict[str, dict[str, float]],
    scores_b: dict[str, dict[str, float]],
    models: Sequence[str],
    case_ids: Sequence[str],
    *, replicates: int, seed: int,
) -> tuple[float, float, float, float]:
    """Paired-case bootstrap CIs for model-level rank concordance.

    The dependency-independent standard-library RNG is used deliberately so
    released Monte Carlo interval endpoints are byte-reproducible across installs.
    """
    # Use one dependency-independent RNG path. Earlier releases selected a NumPy
    # or stdlib implementation according to the local environment; both were
    # statistically valid but produced different Monte Carlo endpoints. A single
    # implementation makes every released CSV byte-reproducible across installs.
    taus: list[float] = []
    rhos: list[float] = []
    n_cases = len(case_ids)
    rng = random.Random(seed)
    for _ in range(replicates):
        sampled = [case_ids[rng.randrange(n_cases)] for _ in range(n_cases)]
        means_a = [statistics.mean(scores_a[model][case_id] for case_id in sampled) for model in models]
        means_b = [statistics.mean(scores_b[model][case_id] for case_id in sampled) for model in models]
        taus.append(kendall_tau_b(means_a, means_b))
        rhos.append(spearman_rho(means_a, means_b))
    return (percentile(taus, 0.025), percentile(taus, 0.975),
            percentile(rhos, 0.025), percentile(rhos, 0.975))


def bootstrap_mean_ci(values: Sequence[float], *, replicates: int, seed: int) -> tuple[float, float]:
    rng = random.Random(seed)
    n = len(values)
    means = [statistics.mean(values[rng.randrange(n)] for _ in range(n)) for _ in range(replicates)]
    return percentile(means, 0.025), percentile(means, 0.975)


def case_stratified_pseudo_self_p(
    case_vectors: Sequence[Sequence[float]], observed: float, *, replicates: int, seed: int
) -> float:
    # Precompute the pseudo-self contrast for choosing each model within each case.
    candidate_effects = [
        [(len(values) * chosen - sum(values)) / (len(values) - 1) for chosen in values]
        for values in case_vectors
    ]
    exceed = 0
    rng = random.Random(seed)
    for _ in range(replicates):
        statistic = statistics.mean(values[rng.randrange(len(values))] for values in candidate_effects)
        if abs(statistic) >= abs(observed) - 1e-15:
            exceed += 1
    return (exceed + 1) / (replicates + 1)


def zscores(values: dict[str, float]) -> dict[str, float]:
    mean = statistics.mean(values.values())
    sd = statistics.pstdev(values.values())
    return {key: ((value - mean) / sd if sd else 0.0) for key, value in values.items()}


def icc_absolute_agreement(matrix: Sequence[Sequence[float]]) -> tuple[float, float]:
    n = len(matrix)
    if n < 2:
        raise ValueError("icc_requires_at_least_two_targets")
    k = len(matrix[0])
    if k < 2 or any(len(row) != k for row in matrix):
        raise ValueError("icc_requires_rectangular_matrix_with_at_least_two_judges")
    grand = statistics.mean(value for row in matrix for value in row)
    row_means = [statistics.mean(row) for row in matrix]
    column_means = [statistics.mean(row[j] for row in matrix) for j in range(k)]
    msr = k * sum((value - grand) ** 2 for value in row_means) / (n - 1)
    msc = n * sum((value - grand) ** 2 for value in column_means) / (k - 1)
    mse = sum(
        (matrix[i][j] - row_means[i] - column_means[j] + grand) ** 2
        for i in range(n) for j in range(k)
    ) / ((n - 1) * (k - 1))
    denom_one = msr + (k - 1) * mse + k * (msc - mse) / n
    denom_average = msr + (msc - mse) / n
    return ((msr - mse) / denom_one if denom_one else 0.0, (msr - mse) / denom_average if denom_average else 0.0)


def expected_grade_from_gate_flags(row: dict[str, Any]) -> int:
    """Reconstruct the immutable ordinal grade from exported canonical flags."""
    serious = bool(row["serious_error_present"])
    minor = bool(row["minor_or_moderate_error_present"])
    important_defect = bool(row["important_non_chain_defect_present"])
    all_good = bool(row["all_dimensions_at_least_good"])
    closure_valid = bool(row["closure_valid"])
    strong = bool(row["strong_gate"])
    perfect = bool(row["perfect_gate"])
    completed_ho = int(row["completed_high_order_count"])

    if perfect and not strong:
        raise ValueError("perfect_gate_without_strong_gate")
    if strong != (not serious and not minor and not important_defect and all_good and closure_valid and completed_ho >= 1):
        raise ValueError("strong_gate_flag_inconsistent")
    if perfect and (completed_ho < 2 or not closure_valid):
        raise ValueError("perfect_gate_flag_inconsistent")
    if serious:
        return 1
    if minor:
        return 2
    if perfect:
        return 5
    if strong:
        return 4
    return 3


def bootstrap_model_cis(
    by_model_case: dict[str, dict[str, float]], case_ids: list[str], *, replicates: int, seed: int
) -> dict[str, tuple[float, float]]:
    if replicates < 1:
        raise ValueError("bootstrap_replicates_must_be_positive")
    rng = random.Random(seed)
    samples: dict[str, list[float]] = {model: [] for model in sorted(by_model_case)}
    for _ in range(replicates):
        draw = [case_ids[rng.randrange(len(case_ids))] for _ in case_ids]
        for model in samples:
            samples[model].append(statistics.mean(by_model_case[model][case_id] for case_id in draw))
    return {model: (percentile(values, 0.025), percentile(values, 0.975)) for model, values in samples.items()}


def analyze(
    *,
    root: Path,
    canonical_scores: Path,
    packet_manifest: Path,
    case_metadata: Path,
    output_dir: Path,
    expected_packets: int,
    expected_judges: int,
    expected_models: int,
    expected_cases: int,
    bootstrap_replicates: int,
    bootstrap_seed: int,
    rank_bootstrap_replicates: int | None = None,
    self_preference_bootstrap_replicates: int | None = None,
    self_preference_permutation_replicates: int | None = None,
) -> dict[str, Any]:
    canonical_scores = resolve(root, canonical_scores)
    packet_manifest = resolve(root, packet_manifest)
    case_metadata = resolve(root, case_metadata)
    output_dir = resolve(root, output_dir)
    rank_bootstrap_replicates = rank_bootstrap_replicates or bootstrap_replicates
    self_preference_bootstrap_replicates = self_preference_bootstrap_replicates or bootstrap_replicates
    self_preference_permutation_replicates = self_preference_permutation_replicates or bootstrap_replicates
    score_rows_raw = read_csv(canonical_scores)
    manifest = json.loads(packet_manifest.read_text(encoding="utf-8"))
    packet_rows = manifest.get("packets")
    if not isinstance(packet_rows, list):
        raise ValueError("packet_manifest_missing_packets")
    if len(packet_rows) != expected_packets:
        raise ValueError(f"packet_count_mismatch:expected_{expected_packets}:got_{len(packet_rows)}")
    packet_by_id: dict[str, dict[str, Any]] = {}
    trajectories: dict[str, dict[str, Any]] = {}
    case_burden_by_case: dict[str, dict[str, Any]] = {}
    for row in packet_rows:
        packet_id = str(row.get("packet_id") or "")
        if not packet_id or packet_id in packet_by_id:
            raise ValueError(f"invalid_or_duplicate_packet_id:{packet_id}")
        path = resolve(root, row["packet_file"])
        if file_sha256(path) != row["packet_sha256"]:
            raise ValueError(f"packet_hash_mismatch:{packet_id}")
        packet = json.loads(path.read_text(encoding="utf-8"))
        case_id = str(row.get("case_id") or "")
        burden_profile = case_contract_burden_profile(packet.get("case_contract") or {})
        prior_profile = case_burden_by_case.get(case_id)
        if prior_profile is not None and prior_profile != burden_profile:
            raise ValueError(f"case_contract_burden_profile_mismatch:{case_id}")
