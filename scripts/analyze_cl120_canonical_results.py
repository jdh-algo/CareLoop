    # Case-level outcomes are reported as outcomes only. They are deliberately not
    # combined into a post-run "difficulty" label: doing so and then showing that
    # score, turn count, or nonclosure varies by that label would be circular.
    case_score = {case_id: statistics.mean(row["aggregate_score_median"] for row in trajectory_rows if row["case_id"] == case_id) for case_id in case_ids}
    case_turns = {case_id: statistics.mean(row["turns_completed"] for row in trajectory_rows if row["case_id"] == case_id) for case_id in case_ids}
