    matrix = [[cells[(packet_id, judge)]["trajectory_grade"] for judge in judges_sorted] for packet_id in sorted(trajectories)]
    icc_one, icc_average = icc_absolute_agreement(matrix)
    agreement_rows: list[dict[str, Any]] = []
