def file_sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def json_sha256(value: Any) -> str:
    """Hash JSON using the frozen Judge protocol's canonical serialization."""
    payload = json.dumps(value, ensure_ascii=False, sort_keys=True, separators=(",", ":"))
    return hashlib.sha256(payload.encode("utf-8")).hexdigest()


def resolve(root: Path, value: Path | str) -> Path:
    path = Path(value)
    return path.resolve() if path.is_absolute() else (root / path).resolve()


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open("r", encoding="utf-8-sig", newline="") as handle:
        return [{str(k).lstrip("\ufeff"): v for k, v in row.items()} for row in csv.DictReader(handle)]


def raw_quality_json(errors: list[str]) -> str:
    return json.dumps(errors, ensure_ascii=False, separators=(",", ":"))


def parse_bool(value: Any, field: str) -> bool:
    if isinstance(value, bool):
        return value
    normalized = str(value).strip().lower()
    if normalized in TRUE:
        return True
    if normalized in FALSE:
        return False
    raise ValueError(f"invalid_boolean:{field}:{value!r}")


def split_multivalue(value: Any) -> list[str]:
    """Parse the public metadata convention for overlapping pipe-separated tags."""
    return [item.strip() for item in str(value or "").split("|") if item.strip()]


def case_contract_burden_profile(case_contract: dict[str, Any]) -> dict[str, Any]:
    """Derive an outcome-independent burden profile from frozen case-contract fields.

    The five component scores are descriptive design burdens, not Judge scores and
    not a retroactive claim of preregistration.  No trajectory result, model score,
    turn count, terminal status, or Judge output is read here.
    """
    try:
        evaluation = case_contract["evaluation_contract_v2"]
        support = evaluation["supporting_evaluation_context"]
        closure = case_contract["closure_contract_v2"]
        friction = case_contract["real_world_friction_design"]
        handoff = closure["handoff_policy"]
    except (KeyError, TypeError) as exc:
        raise ValueError(f"case_contract_burden_fields_missing:{exc}") from exc

    rc_count = len(evaluation.get("responsibility_chain_required_items") or [])
    ho_count = len(evaluation.get("high_order_test_points") or [])
    evidence_channel_count = len(support.get("expected_evidence_channels") or [])
    friction_intensity = str(friction.get("friction_intensity") or "").strip()
    expected_turn_budget = str((closure.get("expected_turn_budget") or {}).get("category") or "").strip()
    expected_closure_within_100 = str((closure.get("expected_turn_budget") or {}).get("expected_closure_within_100") or "").strip()
    required_receipt_count = len(handoff.get("required_receipts") or [])
    blocking_residual_risk_count = len(closure.get("blocking_residual_risks") or [])
    premature_closure_trap_count = len(closure.get("premature_closure_traps") or [])
    handoff_transition_only = bool(handoff.get("handoff_is_transition_only"))

    if not 5 <= rc_count <= 9:
        raise ValueError(f"unexpected_responsibility_chain_count:{rc_count}")
    if ho_count != 4:
        raise ValueError(f"unexpected_high_order_point_count:{ho_count}")
    if evidence_channel_count not in {5, 6, 7, 8}:
        raise ValueError(f"unexpected_evidence_channel_count:{evidence_channel_count}")
    if friction_intensity not in FRICTION_BURDEN_SCORE:
        raise ValueError(f"unexpected_friction_intensity:{friction_intensity}")
    if expected_turn_budget not in TURN_BUDGET_BURDEN_SCORE:
        raise ValueError(f"unexpected_expected_turn_budget:{expected_turn_budget}")
    if expected_closure_within_100 not in {"yes", "maybe", "no"}:
        raise ValueError(f"unexpected_expected_closure_within_100:{expected_closure_within_100}")

    rc_burden = 0 if rc_count <= 6 else 1 if rc_count == 7 else 2
    evidence_burden = 0 if evidence_channel_count <= 5 else 1 if evidence_channel_count == 6 else 2
    friction_burden = FRICTION_BURDEN_SCORE[friction_intensity]
    temporal_burden = TURN_BUDGET_BURDEN_SCORE[expected_turn_budget]
    closure_conditions = sum((
        handoff_transition_only,
        required_receipt_count >= 3,
        blocking_residual_risk_count >= 6,
        premature_closure_trap_count >= 6,
    ))
    closure_burden = 0 if closure_conditions == 0 else 1 if closure_conditions == 1 else 2
    total = rc_burden + evidence_burden + friction_burden + temporal_burden + closure_burden
    level = "low" if total <= 3 else "moderate" if total <= 6 else "high"
    return {
        "responsibility_chain_requirement_count": rc_count,
        "high_order_test_point_count": ho_count,
        "expected_evidence_channel_count": evidence_channel_count,
        "friction_intensity": friction_intensity,
        "expected_turn_budget_category": expected_turn_budget,
        "expected_closure_within_100": expected_closure_within_100,
        "handoff_is_transition_only": handoff_transition_only,
        "required_receipt_count": required_receipt_count,
        "blocking_residual_risk_count": blocking_residual_risk_count,
        "premature_closure_trap_count": premature_closure_trap_count,
        "responsibility_chain_burden_score": rc_burden,
        "responsibility_chain_burden_level": ("low", "moderate", "high")[rc_burden],
        "evidence_integration_burden_score": evidence_burden,
        "evidence_integration_burden_level": ("low", "moderate", "high")[evidence_burden],
        "friction_burden_score": friction_burden,
        "friction_burden_level": ("low", "moderate", "high")[friction_burden],
        "temporal_burden_score": temporal_burden,
        "temporal_burden_level": ("low", "moderate", "high")[temporal_burden],
        "closure_coordination_burden_score": closure_burden,
        "closure_coordination_burden_level": ("low", "moderate", "high")[closure_burden],
        "contract_complexity_index": total,
        "contract_complexity_level": level,
    }


def public_trajectory_metrics(path: Path, *, expected_sha256: str) -> dict[str, Any]:
    """Read only outcome-independent execution metadata from a frozen trajectory.

    The historical ``scores``, ``quality_report_public``, and empirical difficulty
    fields are intentionally ignored.  This prevents withdrawn analysis outputs
    embedded in the source trajectory from leaking into the canonical analysis.
    """
    actual_sha256 = file_sha256(path)
    if actual_sha256 != expected_sha256:
        raise ValueError(f"source_trajectory_hash_mismatch:{path}")
    document = json.loads(path.read_text(encoding="utf-8"))
    events = document.get("events_public")
    if not isinstance(events, list) or not all(isinstance(event, dict) for event in events):
        raise ValueError(f"source_trajectory_events_invalid:{path}")

    def count(event_type: str) -> int:
        return sum(event.get("event_type") == event_type for event in events)

    doctor_turns = sorted({int(event["turn"]) for event in events if event.get("event_type") == "doctor_message"})
    workspace_turns = sorted({int(event["turn"]) for event in events if event.get("event_type") == "doctor_workspace_message"})
    runtime = document.get("runtime_error_public") or {}
    closure = document.get("closure_public") or {}
    turns_completed = int(document.get("turns_completed", 0))
    workspace_turn_count = len(workspace_turns)
    return {
        "source_trajectory_file": str(path),
        "source_public_trajectory_id": str(document.get("public_trajectory_id") or ""),
        "source_case_id": str(document.get("case_id") or ""),
        "source_doctor_model": str(document.get("doctor_model") or ""),
        "source_terminal_status": str(document.get("terminal_status") or ""),
        "source_turns_completed": turns_completed,
        "retained_event_count": len(events),
        "doctor_message_count": count("doctor_message"),
        "doctor_turn_count": len(doctor_turns),
        "workspace_turn_count": workspace_turn_count,
        "workspace_entry_count": count("doctor_workspace_message"),
        "workspace_result_count": count("doctor_workspace_result"),
        # This is the exact public event corresponding to the old analysis'
        # doctor_operation_routing_count.
        "doctor_operation_routing_count": count("clinical_workspace_response"),
        "has_workspace": workspace_turn_count > 0,
        "turns_per_workspace_turn": turns_completed / workspace_turn_count if workspace_turn_count else "",
        "first_workspace_turn": workspace_turns[0] if workspace_turns else "",
        "last_workspace_turn": workspace_turns[-1] if workspace_turns else "",
        "family_message_count": count("family_message"),
        "patient_message_count": count("patient_message"),
        "doctor_system_notification_count": count("doctor_system_notification"),
        "runtime_error_category": str(runtime.get("runtime_error_category") or ""),
        "runtime_error_type": str(runtime.get("runtime_error_type") or ""),
        "runtime_error_message_excerpt": str(runtime.get("runtime_error_message_excerpt") or ""),
        "closure_status": str(closure.get("status") or ""),
        "closure_kind": str(closure.get("closure_kind") or ""),
    }


