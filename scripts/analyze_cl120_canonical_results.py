def bootstrap_case_correlation(
    x: Sequence[float], y: Sequence[float], *, replicates: int, seed: int
) -> dict[str, float]:
    if len(x) != len(y) or len(x) < 2:
        raise ValueError("correlation_requires_equal_sequences_of_length_at_least_two")
    rng = random.Random(seed)
    rhos: list[float] = []
    taus: list[float] = []
    for _ in range(replicates):
        draw = [rng.randrange(len(x)) for _ in x]
        bx = [x[index] for index in draw]
        by = [y[index] for index in draw]
        rhos.append(spearman_rho(bx, by))
        taus.append(kendall_tau_b(bx, by))
    return {
        "spearman_rho": spearman_rho(x, y),
        "spearman_rho_ci95_low": percentile(rhos, 0.025),
        "spearman_rho_ci95_high": percentile(rhos, 0.975),
        "kendall_tau_b": kendall_tau_b(x, y),
        "kendall_tau_b_ci95_low": percentile(taus, 0.025),
        "kendall_tau_b_ci95_high": percentile(taus, 0.975),
    }


def atomic_text(path: Path, text: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_text(text, encoding="utf-8")
    os.replace(temporary, path)


def atomic_csv(path: Path, rows: list[dict[str, Any]], fieldnames: Sequence[str] | None = None) -> None:
    if not rows and fieldnames is None:
        raise ValueError(f"empty_rows_without_schema:{path.name}")
    names = list(fieldnames or rows[0].keys())
    temporary = path.with_name(path.name + ".tmp")
    with temporary.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=names, extrasaction="raise", lineterminator="\n")
        writer.writeheader()
        writer.writerows(rows)
    os.replace(temporary, path)


